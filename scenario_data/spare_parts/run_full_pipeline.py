# Force in-process execution: replace celery dispatch with a no-op so
# the API call returns an active_job_id but doesn't actually queue. We
# then drive JobExecutionService.execute_job() directly with the latest
# code in this Python process — bypasses any stale celery worker.
_ORIG_DISPATCH = job_dispatch_service.JobDispatchService.dispatch
job_dispatch_service.JobDispatchService.dispatch = (
    lambda self, job_id: ("inprocess", f"task-{job_id}")
)

