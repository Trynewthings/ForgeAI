"""End-to-end driver: existing seeded session → build → run → check output.

The session was seeded by ``driver.py`` (Stage 0/1) and its node_specs
were re-generated by ``run_specify.py`` (v4, edge_contract PASSED).
This script kicks off build + run via the in-process FastAPI app
(uses live Postgres + latest code, no dependency on the running uvicorn
which may be stale).

Acceptance:
    1. build completes (status=completed)
    2. bindings.json on disk carries spec-driven task_prompt
       (CONTRACT-BOUND CONSUMPTION wording present in coding_agent
       system_prompt)
    3. run completes (status=completed)
    4. output CSV exists at the declared delivery_target path
    5. Test_Cases ground-truth comparison: how many of the 9 cases pass

Usage:
    python3 scenario_data/spare_parts/run_full_pipeline.py
"""
