OUTPUT_PATH = ROOT / "output" / "replenishment_queue.csv"
TEST_CASES_CSV = ROOT / "expected" / "test_cases.csv"

SESSION_ID = "eb2105c0-caa6-4a66-b42a-f888baeca2f5"


def dump(stage: str, payload: Any) -> Path:
    path = TRACE / f"{stage}.json"
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2, default=str)
    )
    print(f"  -> wrote {path.name}")
    return path


def verify_state_has_passing_specs() -> dict:
    """Read the latest planner-output state for SESSION_ID and confirm
    node_specs_json is present + edge_contract has zero issues."""
    db = SessionLocal()
    try:
        row = (
            db.query(FrontChainState)
            .filter(
                FrontChainState.session_id == SESSION_ID,
                FrontChainState.planner_output_json.isnot(None),
            )
            .order_by(FrontChainState.created_at.desc())
            .first()
        )
        if row is None:
            raise SystemExit(f"no planner-output state for session {SESSION_ID}")
        if not row.node_specs_json:
            raise SystemExit(
                f"state {row.id} has no node_specs_json — re-run /specify first"
            )
        report = (row.node_specs_json or {}).get("edge_contract_report") or {}
        issues = report.get("issues") or []
        if issues:
            raise SystemExit(
                f"node_specs_json has {len(issues)} unresolved edge_contract issues; "
                "re-run /specify to clear before running build."
            )
        project_id = row.project_id
        return {
            "state_id": row.id,
            "project_id": project_id,
            "spec_count": len(row.node_specs_json.get("specs") or []),
            "skipped": list(row.node_specs_json.get("skipped_node_ids") or []),
        }
    finally:
        db.close()


def poll_build(client: TestClient, build_id: str, timeout_s: int = 300) -> dict:
    """Build is dispatched async-via-thread; poll until terminal."""
    t0 = time.time()
    while time.time() - t0 < timeout_s:
        r = client.get(f"/api/v1/builds/{build_id}")
        if r.status_code != 200:
            raise SystemExit(f"GET /builds/{build_id} -> {r.status_code} {r.text}")
        data = r.json()
        if data["status"] in {"completed", "failed"}:
            return data
        time.sleep(2)
    raise SystemExit(f"build {build_id} did not terminate within {timeout_s}s")


def poll_run(client: TestClient, run_id: str, timeout_s: int = 900) -> dict:
    t0 = time.time()
    while time.time() - t0 < timeout_s:
        r = client.get(f"/api/v1/runs/{run_id}")
        if r.status_code != 200:
            raise SystemExit(f"GET /runs/{run_id} -> {r.status_code} {r.text}")
        data = r.json()
        if data["status"] in {"completed", "failed", "waiting_for_intervention"}:
            return data
        time.sleep(3)
    raise SystemExit(f"run {run_id} did not terminate within {timeout_s}s")


def render_test_case_summary(rows: list[dict]) -> None:
    print(f"  test_cases ground-truth: {len(rows)} rows")
    for r in rows[:9]:
        tc = r.get("test_id", r.get("TC_ID", "?"))
        scenario = r.get("scenario", r.get("Scenario", ""))[:40]
        print(f"    {tc:6s} {scenario}")


def compare_against_test_cases(output_csv: Path) -> dict:
    """Lightweight comparison: how many Test_Cases SKUs appear in output
    AND have plausible decisions. Returns a counts dict so caller can
    print a verdict.
    """
    if not output_csv.exists():
        return {"error": "output csv missing"}

    with open(output_csv, "r", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    if not rows:
        return {"error": "output csv is empty"}

    output_skus = {r.get("sku_id") or r.get("SKU") or r.get("sku") for r in rows}
    output_skus.discard(None)

    if not TEST_CASES_CSV.exists():
        return {"output_rows": len(rows), "test_cases_csv_missing": True}

    with open(TEST_CASES_CSV, "r", encoding="utf-8") as fh:
        cases = list(csv.DictReader(fh))

    expected_skus = set()
    for c in cases:
        scenario = (c.get("scenario") or "")
        # Test_Cases scenarios mention specific SKUs like "P-001".
        import re

        for m in re.findall(r"P-\d{3}", scenario):
            expected_skus.add(m)

    overlap = expected_skus & output_skus
    return {
        "output_rows": len(rows),
        "output_skus": len(output_skus),
        "test_case_skus": sorted(expected_skus),
        "overlap_count": len(overlap),
        "overlap": sorted(overlap),
    }


def main() -> int:
    print("\n[stage 0] verify seeded session has passing node_specs")
    state_info = verify_state_has_passing_specs()
    print(
        f"  state_id={state_info['state_id']}  spec_count={state_info['spec_count']}  "
        f"skipped={state_info['skipped']}"
    )
    project_id = state_info["project_id"]

    # Make sure the output directory exists and starts empty.
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    if OUTPUT_PATH.exists():
        OUTPUT_PATH.unlink()
        print(f"  cleared previous output at {OUTPUT_PATH}")

    with TestClient(app) as client:
        # ---------- Stage 1: create + start + poll build ----------
        print("\n[stage 1] build (create + start + poll)")
        build_resp = client.post(
            "/api/v1/builds",
            json={
                "project_id": project_id,
                "session_id": SESSION_ID,
                "build_options_json": {"target": "spare_parts_full_pipeline"},
            },
        )
        if build_resp.status_code != 201:
            raise SystemExit(f"POST /builds -> {build_resp.status_code} {build_resp.text}")
        build_id = build_resp.json()["id"]
        print(f"  build_id={build_id}")

        started = client.post(f"/api/v1/builds/{build_id}/start")
        if started.status_code != 200:
            raise SystemExit(f"POST /builds/{build_id}/start -> {started.status_code} {started.text}")
        job_id = started.json().get("active_job_id")
        print(f"  job_id={job_id}  (executing in-process)")
        # In-process execution — uses the latest task 4 code (spec gates etc).
        JobExecutionService().execute_job(job_id)
        build_final = poll_build(client, build_id, timeout_s=10)
        dump("06_build_final", build_final)
        print(f"  build.status={build_final['status']}")
        if build_final["status"] != "completed":
            print(f"  ✗ error_message={build_final.get('error_message')}")
            return 2
        executable_id = build_final["executable_id"]

        # Inspect bindings.json on disk → contract-bound system_prompt?
        exe = client.get(f"/api/v1/executables/{executable_id}").json()
        source_path = Path(exe["source_path"])
        bindings_file = source_path / "bindings.json"
        if not bindings_file.exists():
            print(f"  ✗ bindings.json missing at {bindings_file}")
            return 3
        bindings = json.loads(bindings_file.read_text())["bindings"]
        coding_bindings = [
            b for b in bindings if b["selected_capability_id"] == "coding_agent"
        ]
        print(f"  bindings: {len(bindings)} total, {len(coding_bindings)} coding_agent")
        if coding_bindings:
            sample = coding_bindings[0]
            sys_prompt = sample.get("config_hints", {}).get("system_prompt", "")
            task_prompt = sample.get("config_hints", {}).get("task_prompt", "")
            has_contract_rule = "Contract-bound data access" in sys_prompt
            print(f"  contract-bound rule in system_prompt: {has_contract_rule}")
            print(f"  task_prompt length: {len(task_prompt)}  (placeholder would be ~50)")

        # ---------- Stage 2: create + start + poll run ----------
        print("\n[stage 2] run (create + start + poll)")
        run_resp = client.post(
            "/api/v1/runs",
            json={
                "project_id": project_id,
                "executable_id": executable_id,
                "input_snapshot_json": {},
            },
        )
        if run_resp.status_code != 201:
            raise SystemExit(f"POST /runs -> {run_resp.status_code} {run_resp.text}")
        run_id = run_resp.json()["id"]
        steps = run_resp.json().get("run_steps") or []
        print(f"  run_id={run_id}  steps={[s['step_name'] for s in steps]}")

        started_run = client.post(f"/api/v1/runs/{run_id}/start")
        if started_run.status_code != 200:
            raise SystemExit(f"POST /runs/{run_id}/start -> {started_run.status_code} {started_run.text}")
        run_job_id = started_run.json().get("active_job_id")
        print(f"  run_job_id={run_job_id}  (executing in-process)")
        JobExecutionService().execute_job(run_job_id)
        run_final = poll_run(client, run_id, timeout_s=10)
        dump("07_run_final", run_final)
        print(f"  run.status={run_final['status']}")

        # ---------- Stage 3: check output + compare to ground truth ----------
        print("\n[stage 3] inspect output + compare to ground truth")
        if not OUTPUT_PATH.exists():
            print(f"  ✗ output CSV missing at {OUTPUT_PATH}")
            return 4
        size = OUTPUT_PATH.stat().st_size
        print(f"  ✓ output CSV exists at {OUTPUT_PATH}  size={size}B")
        head_lines = OUTPUT_PATH.read_text(errors="replace").splitlines()[:6]
        for line in head_lines:
            print(f"    {line}")

        comparison = compare_against_test_cases(OUTPUT_PATH)
        dump("08_test_case_comparison", comparison)
        print()
        print("  Test_Cases comparison:")
        for k, v in comparison.items():
            print(f"    {k}: {v}")

        return 0 if run_final["status"] == "completed" else 1


if __name__ == "__main__":
    sys.exit(main())
